public class Variable {
    public  static  void main()
    {
        //System.out.println("age");
        //create, declare
        int age = 11;
        System.out.println("age");
        //assign value
        age = 13;
        age = 19;
        System.out.println(age);

        //define or initialize
        int totalMarks = 20;
        System.out.println(totalMarks);

        //case sensitive
        int weight = 50;
        int WEIGHT = 79;
        System.out.println("wieght:" + weight);
        System.out.println("WEIGHT" + WEIGHT);

    }
            

    
    
}